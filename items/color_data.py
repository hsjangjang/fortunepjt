def color_name_to_hex(color_name):
    """색상 이름을 HEX로 변환"""
    color_name_lower = color_name.lower()

    # 정확한 매칭
    if color_name_lower in COLOR_NAME_TO_HEX:
        return COLOR_NAME_TO_HEX[color_name_lower]

    for key, hex_val in COLOR_NAME_TO_HEX.items():
        if color_name_lower == key:
            return hex_val

    # 부분 매칭
    for key, hex_val in COLOR_NAME_TO_HEX.items():
        if key in color_name_lower or color_name_lower in key:
            return hex_val

    # 키워드 기반 매칭
    for keywords, hex_val in COLOR_KEYWORDS:
        if any(kw in color_name_lower for kw in keywords):
            return hex_val

    # 기본값 (회색)
    print(f"[WARNING] 알 수 없는 색상: {color_name}, 회색으로 표시")
    return '#6B7280'


def english_to_korean_color(english_name):
    """영문 색상명을 한글로 변환"""
    return ENGLISH_TO_KOREAN.get(english_name.lower(), english_name)


def are_similar_colors(color1, color2):
    """두 색상이 유사한지 확인"""
    for group in SIMILAR_COLOR_GROUPS:
        if color1 in group and color2 in group:
            return True
    return False
