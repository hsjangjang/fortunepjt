def get_lucky_color_to_ootd(lucky_color: str) -> list:
    """행운색을 OOTD 색상 목록으로 변환"""
    return LUCKY_COLOR_TO_OOTD.get(lucky_color, [lucky_color])


def get_food_color_keywords(lucky_color: str) -> list:
    """행운색을 음식 색상 키워드 목록으로 변환"""
    return LUCKY_COLOR_TO_FOOD.get(lucky_color, [lucky_color.lower()])


def get_korean_color(eng_color: str) -> str:
    """영어 색상을 한글로 변환"""
    eng_color = eng_color.split('/')[0].lower()
    for k, v in ENG_TO_KOR_COLOR.items():
        if k in eng_color:
            return v
    return '기타'


def get_color_gradient(color: str) -> str:
    """색상에 맞는 그라데이션 반환"""
    return COLOR_GRADIENTS.get(color, 'linear-gradient(135deg, #667eea, #764ba2)')
